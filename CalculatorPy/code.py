a = float(input("Enter the 1st Number: "))
b = float(input("Enter the 2nd Number: "))

op = input("Enter operator(+,-,*,/,%,**): ")

if op == '+':
    print(a+b)
elif op == '-':
    print(a-b)
elif op == '*':
    print(a*b)
elif op == '/':
    print(a/b)
elif op == '%':
    print(a%b)
elif op == '**':
    print(a**b)
else:
    print("INVALID OPERATION")


           





